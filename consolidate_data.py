reader = csv.DictReader(io.StringIO(raw_csv))
for row in reader:
    # Clean the amounts
    buy = int(row['قیمت خرید'].replace('.','')) if row['قیمت خرید'] else None
    sell = int(row['قیمت فروش'].replace('.','')) if row['قیمت فروش'] else None
