import json
import logging
from telegram import (
    Update,
    InlineKeyboardMarkup,
    InlineKeyboardButton,
)
from telegram.ext import CallbackContext
from core import config
from core.security import is_authorized_admin, admin_required
from ai import engine as ai_engine
from services import marketing_service
from handlers.customer import fallback_unknown
from handlers.pricing import handle_ai_price_input

logger = logging.getLogger(__name__)

def admin_chat_router(update: Update, context: CallbackContext) -> None:
    """Routes incoming text messages: handles AI pricing flow or admin natural language commands."""
    # 1. Check if update has valid message and private chat
    if not update or not update.message or not update.message.text or not update.effective_chat:
        return fallback_unknown(update, context)

    if update.effective_chat.type != 'private':
        return

    if context.user_data.get('awaiting_ai_price'):
        return handle_ai_price_input(update, context)
        
    user = update.effective_user
    if not user or not is_authorized_admin(user.id):
        return fallback_unknown(update, context)
        
    text = update.message.text.strip()
    if text.startswith("/"):
        return

    try:
        reply_msg = ai_engine.process_admin_message(text)
        
        # Check if agent output contains JSON channel draft
        is_json_draft = False
        try:
            payload = json.loads(reply_msg)
            if isinstance(payload, dict) and payload.get("action") == "channel_draft":
                is_json_draft = True
                draft_text = payload.get("text", "")
                imei = payload.get("imei", "")
                proposed_price = payload.get("proposed_price", 0.0)
                
                msg_body = (
                    "📝 **پیش‌نویس پست کانال برای تایید (HITL Approval):**\n\n"
                    f"{draft_text}\n\n"
                    f"💰 قیمت پیشنهادی: {proposed_price} تومان\n"
                    f"🆔 شناسه دستگاه: {imei}"
                )
                
                keyboard = [
                    [
                        InlineKeyboardButton("✅ تایید و ارسال", callback_data=f"ai_draft_approve_{imei}"),
                        InlineKeyboardButton("❌ رد کردن", callback_data="ai_draft_reject")
                    ]
                ]
                reply_markup = InlineKeyboardMarkup(keyboard)
                update.message.reply_text(msg_body, reply_markup=reply_markup, parse_mode="Markdown")
        except Exception:
            pass
            
        if not is_json_draft:
            update.message.reply_text(reply_msg)
            
    except Exception as e:
        logger.error(f"Error in admin_chat_router: {e}")
        update.message.reply_text("❌ خطایی در پردازش پیام توسط هوش مصنوعی رخ داد.")

@admin_required
def handle_ai_draft_decision(update: Update, context: CallbackContext) -> None:
    """Handles Approve / Reject decisions on channel drafts generated by the AI agent."""
    query = update.callback_query
    query.answer()
    data = query.data
    
    if data == "ai_draft_reject":
        query.edit_message_text("❌ پیشنویس پست کانال رد و حذف شد.")
        return
        
    if data.startswith("ai_draft_approve_"):
        imei = data.replace("ai_draft_approve_", "")
        msg_text = query.message.text
        lines = msg_text.split("\n\n")
        original_body = lines[1] if len(lines) > 1 else msg_text
        
        # Pick matching photo from iphone/ catalog
        from image_matcher import find_best_image
        catalog_image = find_best_image(original_body)
        
        if config.CHANNEL_ID:
            try:
                success, err_msg = marketing_service.publish_post_detailed(
                    chat_id=query.message.chat_id,
                    text=original_body,
                    image_path=catalog_image,
                    channel_id=config.CHANNEL_ID
                )
                if success:
                    query.edit_message_text(f"✅ پست همراه با تصویر با موفقیت به کانال ارسال شد:\n\n{original_body}")
                else:
                    query.edit_message_text(f"⚠️ تایید شد اما ارسال به کانال با خطا مواجه شد:\n{err_msg}")
            except Exception as e:
                logger.error(f"Failed to post draft to channel: {e}")
                query.edit_message_text(f"⚠️ تایید شد اما ارسال به کانال با خطا مواجه گردید: {e}")
        else:
            query.edit_message_text(f"✅ تایید شد! شناسه دستگاه: {imei}. (شناسه کانال CHANNEL_ID تنظیم نشده است)")
